#!/usr/bin/env python3
"""
build-data.py — merges the machine facts with the human copy.

    tools/asset-manifest.json   (durations, posters, pixel dimensions)
  + tools/content-meta.json     (titles, blurbs, prices, gallery placeholders)
  + tools/youtube-thumbs.json   (cover photos for the films supplied as links)
  ->  js/course-data.js         window.CAS_COURSES
  ->  js/gallery-data.js        window.CAS_GALLERY

Durations always come from the manifest (i.e. from ffprobe). Nothing here
invents a runtime. Run tools/import-assets.py first.

Every record that carries an image also carries the four fields a responsive
<img> needs, spelled exactly:

    srcset  "img/gallery/g01-320.jpg 320w, ... , img/gallery/g01.jpg 1600w"
    sizes   the slot's `sizes` attribute, measured from the rendered page
    w, h    the master's intrinsic pixels, for width/height (no layout shift)

They describe the record's PRIMARY image — a course's `cover`, a lesson's
`poster`, a gallery piece's `img`, a free video's `poster`. Where a record has
more than one image the extras get their own object with the same four keys:
`photosMeta[i]` lines up with `photos[i]`, and a course's `cardCoverMeta`,
`cardPhotoMeta` and `highlightPosterMeta` line up with `cardCover`, `cardPhoto`
and `highlightPoster`.

Usage:  python tools/build-data.py
"""

import json
import os
import sys

SITE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOOLS = os.path.join(SITE_DIR, "tools")
JS = os.path.join(SITE_DIR, "js")

BANNER = ("/* GENERATED by tools/build-data.py — do not hand-edit.\n"
          "   Facts (durations, posters, ratios): tools/asset-manifest.json\n"
          "   Copy   (titles, blurbs, prices):    tools/content-meta.json\n"
          "   Re-run: python tools/import-assets.py && python tools/build-data.py */\n")


STATIC_HELPER = (
    "\n"
    "/* ticket 17. The pages that write their own <img> tags — About's photo\n"
    "   strips and certificates, Showcase's wall, the Gallery quick-view — look\n"
    "   their file up here rather than carrying a copy of the ladder in the\n"
    "   markup. Key is the src exactly as the page writes it ('img/...').\n"
    "   `sizes` may be overridden per call: the same file is painted at 584px in\n"
    "   About's portrait and at 36px in a byline avatar. */\n"
    "window.CAS_IMG_ATTRS = function (src, sizes) {\n"
    "  var m = (window.CAS_IMG || {})[src];\n"
    "  if (!m) return '';\n"
    "  var esc = function (s) { return String(s).replace(/&/g, '&amp;').replace(/\"/g, '&quot;').replace(/</g, '&lt;'); };\n"
    "  return ' srcset=\"' + esc(m.srcset) + '\"'\n"
    "       + ' sizes=\"' + esc(sizes || m.sizes) + '\"'\n"
    "       + ' width=\"' + m.w + '\" height=\"' + m.h + '\"';\n"
    "};\n"
)


def load(path):
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def load_video_links():
    """Source filename -> Google Drive preview URL (tools/video-links.json).
    Optional: with no links file every video field stays null and the player
    falls back to the simulated demo."""
    path = os.path.join(TOOLS, "video-links.json")
    if not os.path.exists(path):
        return {}
    ids = load(path).get("files", {})
    return {name: "https://drive.google.com/file/d/%s/preview" % fid
            for name, fid in ids.items() if fid}


def img_fields(meta):
    """Spread an import-assets image meta over the four field names the pages
    read. A record whose image does not exist gets nulls rather than missing
    keys, so `if (rec.srcset)` is the whole of a page's branching."""
    if not meta:
        return {"srcset": None, "sizes": None, "w": None, "h": None}
    return {"srcset": meta["srcset"], "sizes": meta["sizes"],
            "w": meta["w"], "h": meta["h"]}


def duration_bucket(total_seconds):
    """Five bands, not three (client feedback 2026-08-08). With three, every
       course over two hours fell into one chip and the filter stopped telling
       you anything. Labels live in js/filter-tags.js and must match these keys:
       xs = 'Under 30m', short = '30m-1h', medium = '1-2h', long = '2-4h',
       xl = '4h+'."""
    if total_seconds < 1800:
        return "xs"
    if total_seconds < 3600:
        return "short"
    if total_seconds < 7200:
        return "medium"
    if total_seconds < 14400:
        return "long"
    return "xl"


def _films(entries, links, slug):
    """Resolve course-level films to playable urls, dropping any that cannot play."""
    out = []
    for f in entries:
        url = links.get(f["src"])
        if not url:
            print("  ! %s: film %r has no Drive id in tools/video-links.json, not shipped"
                  % (slug, f["src"]))
            continue
        out.append({"title": f["title"], "desc": f.get("desc") or "", "url": url,
                    "src": f["src"]})
    return out


def build_courses(manifest, meta, links):
    by_slug = {c["slug"]: c for c in manifest["courses"]}
    out = []

    for slug, copy in meta["courses"].items():
        asset = by_slug.get(slug)
        if not asset:
            print("  ! no assets for %s — skipped" % slug)
            continue

        a_lessons, c_lessons = asset["lessons"], copy["lessons"]
        if len(a_lessons) != len(c_lessons):
            print("  ! %s: %d asset lessons vs %d written lessons — using the shorter"
                  % (slug, len(a_lessons), len(c_lessons)))

        lessons = []
        for i, (al, cl) in enumerate(zip(a_lessons, c_lessons)):
            if al["dur"] is None:
                print("  ! %s lesson %d has no duration" % (slug, i + 1))
            # A lesson may be multi-part (several videos in its folder).
            # Every part gets its own Drive URL; the player shows part pills
            # when there is more than one. "video" stays as part 1's URL so
            # older readers keep working.
            raw_parts = al.get("videos") or (
                [{"file": al["srcVideo"], "dur": al["dur"]}] if al.get("srcVideo") else [])
            parts = []
            for j, pt in enumerate(raw_parts):
                url = links.get(pt["file"])
                if not url:
                    print("  ! %s lesson %d part %s has no Drive link — part dropped"
                          % (slug, i + 1, pt["file"]))
                    continue
                # 1.4.12: the container ratio follows the file, not a guess.
                parts.append({"label": "Part %d" % (j + 1), "dur": pt["dur"],
                              "url": url, "src": pt["file"],
                              "portrait": bool(pt.get("portrait"))})
            if len(parts) == 1:
                parts[0]["label"] = ""

            # Focus / tools / outcome come from the client's course introduction
            # docs. Optional: a lesson without them renders no detail panel
            # rather than three empty rows.
            detail = {k: cl[k] for k in ("focus", "tools", "outcome") if cl.get(k)}

            lesson = {
                # her own numbering, which is not the row index: one film can
                # carry two of her lessons (see `spans`), so the numbers run
                # 1, 2 & 3, 4 ... 14 across 13 rows
                "n": al.get("n", i + 1),
                "spans": al.get("spans", 1),
                "title": cl["title"],
                "subtitle": cl["subtitle"],
                # 18.1: a lesson whose copy has not arrived is flagged so the
                # player can say so on the page rather than look finished.
                "pending": bool(cl.get("pending")),
                "detail": detail,
                "dur": al["dur"],                 # seconds, ffprobe; sum of parts
                "poster": al["poster"],
                "video": parts[0]["url"] if parts else None,
                "portrait": bool(parts and parts[0].get("portrait")),
                "videos": parts if len(parts) > 1 else [],
                # Lesson 1 is the free preview — but ONLY where there is
                # something left behind the paywall. little-house and
                # urban-sketch each hold a single lesson, so marking it free
                # gave away the whole GBP24 product: the syllabus rendered one
                # unlocked row badged FREE PREVIEW beside a live Add to cart,
                # and lockedRows was 0. A one-lesson course has no preview.
                # (audit ticket 15, 2026-08-09)
                "free": i == 0 and len(a_lessons) > 1,
                "src": al.get("srcVideo"),        # provenance only, never fetched
                "srcFolder": al["srcFolder"],
                # The photographs the lesson is painted FROM, shown in the lesson
                # body with a download link under each. Only six of the beginner
                # folders carry any; the block does not render when the list is
                # empty. `src` is the client's own filename and is the only label
                # these have -- she supplied no captions, and one written here
                # would be invented. (client feedback 2026-08-12)
                "refPhotos": [
                    dict({"path": r["path"], "src": r["src"]}, **img_fields(r.get("meta")))
                    for r in al.get("refPhotos", [])
                ],
            }
            # srcset/sizes/w/h describe `poster`. `sizes` is written for the
            # 76-78px thumbnail the poster is painted in on course.dc.html and
            # lesson.dc.html; the one place that paints it big — the lesson
            # stage — must set its own `sizes`, or leave it off entirely and
            # take the 100vw default, which lands on the master.
            lesson.update(img_fields(al.get("posterMeta")))
            lessons.append(lesson)

        total = sum(l["dur"] or 0 for l in lessons)
        # What the page calls the lesson count: her numbering, not the row
        # count. 13 films, 14 lessons.
        lesson_count = sum(l.get("spans", 1) for l in lessons)
        # 5.1: one title field carries "short topic - full title", separated by a
        # hyphen. The New Release card shows the topic; every other surface shows
        # the full title. Splitting here means no page has to know the convention,
        # and a title typed without a hyphen still yields a usable full title.
        topic, _, full = [s.strip() for s in copy["title"].partition(" - ")]
        if not full:
            topic, full = "", topic
        course = {
            "id": slug,
            "title": full,
            "topic": topic,
            "tag": copy["tag"],
            "cat": copy["cat"],
            "theme": copy["theme"],
            "difficulty": copy["difficulty"],
            "durationBucket": duration_bucket(total),
            "totalSeconds": total,
            "price": copy["price"],
            "was": copy["was"],
            "sale": bool(copy["sale"]),
            "cover": asset["cover"],
            # 1.4.9 lists materials[] as a per-course field. Crystal has supplied
            # none; the beginner course carries a developer placeholder set so
            # 8.1's bundled + per-item download behaviour is demonstrable, and
            # the others render the empty state rather than borrowing its files.
            "materials": copy.get("materials") or [],
            # Course-level FILMS (2026-08-17). Three instructional videos the
            # client supplied for the beginner course. They belong to no lesson
            # folder — they sit at the course root beside the highlights reel —
            # so they are neither lesson parts nor downloadable materials: the
            # files are 140-215 MB and stream from Drive.
            #
            # content-meta.json names them by SOURCE FILENAME only. The Drive id
            # stays in video-links.json, exactly as every lesson part does, so
            # there is one place a re-upload has to be re-looked-up. A film whose
            # filename is not in that lookup is DROPPED with a warning rather
            # than shipped with a dead url, because a play button that opens an
            # empty Drive frame looks like a broken lesson, not a missing file.
            "films": _films(copy.get("films") or [], links, slug),
            # 7.1: the preview reel for the right-hand column, and the five
            # course photographs (one large, four small) for the thumbnail row.
            "preview": (
                {"url": links.get(asset["highlights"]["file"]),
                 "dur": asset["highlights"]["dur"],
                 "src": asset["highlights"]["file"]}
                if asset.get("highlights") and links.get(asset["highlights"]["file"]) else None
            ),
            "photos": [p["img"] for p in asset.get("photos") or []],
            # index-for-index with `photos`. photosMeta[0] is written for the
            # 446px lead shot, the rest for the 104px thumbnail strip.
            "photosMeta": [img_fields(p.get("meta")) for p in asset.get("photos") or []],
            # 2026-08-16 asset drop. Three images the client named for one slot
            # each: the two the HOME course card paints (its cover and the photo
            # under it) and the poster frame for the course's highlights video.
            # Each is optional — a course the client named no file for carries
            # null here and the four img_fields keys are null too, so a page
            # branches on `if (c.cardCover)` exactly as it does on `c.srcset`.
            # Paths, not attributes: `cardCover` etc. are site-relative srcs and
            # the ladder lives in the matching *Meta object, the same split as
            # `photos` / `photosMeta`.
            "cardCover": asset.get("cardCover"),
            "cardCoverMeta": img_fields(asset.get("cardCoverMeta")),
            "cardPhoto": asset.get("cardPhoto"),
            "cardPhotoMeta": img_fields(asset.get("cardPhotoMeta")),
            "highlightPoster": asset.get("highlightPoster"),
            "highlightPosterMeta": img_fields(asset.get("highlightPosterMeta")),
            "blurb": copy["blurb"],
            # 7.1: `about` is her ABOUT THIS COURSE section as she wrote it,
            # paragraph by paragraph. `blurb` stays a single string because the
            # course cards and the meta description need one. `subline` is the
            # line she puts under the course title.
            "about": copy.get("about") or [],
            "subline": copy.get("subline") or "",
            "learn": copy["learn"],
            "who": copy["who"],
            "modules": copy["modules"],
            "lessonCount": lesson_count,
            "lessons": lessons,
        }
        # srcset/sizes/w/h on the course itself describe `cover`.
        course.update(img_fields(asset.get("coverMeta")))
        out.append(course)
        print("   %-22s %2d lessons (%d rows)  %5ds  %s" % (slug, lesson_count, len(lessons), total,
                                                 duration_bucket(total)))
    return out


def build_free_videos(manifest, meta, links, yt_thumbs):
    """Free videos come from TWO places now, so the copy leads and the manifest follows.

    Until 2026-08-16 every free video was a file the client had uploaded, so
    walking the manifest and looking the copy up by slug was the same thing as
    walking the copy. Then she supplied twelve films as YouTube links rather than
    files. A YouTube record has no file, so it has no manifest entry, so under the
    old loop it could never be emitted no matter what was written about it — the
    records existed in content-meta.json and the page rendered nothing.

    The order of the rails is therefore the order of `content-meta.json`, which is
    the file a human edits, and the manifest supplies posters and durations for
    the records that have one.
    """
    out = []
    by_slug = {fv["slug"]: fv for fv in manifest["freeVideos"]}
    for slug, copy in meta["freeVideos"].items():
        if slug.startswith("_"):
            continue               # a note, or a record parked pending client input
        host = copy.get("host", "drive")
        item = {
            "slug": slug,
            "title": copy["title"],
            "desc": copy.get("desc", ""),
            "section": copy["section"],
            "host": host,
        }
        if host == "youtube":
            # The cover comes from tools/fetch-youtube-thumbs.py, which downloads
            # the one YouTube publishes for the id and puts it through the same
            # encoder as every other image on the site. This used to emit
            # poster: None on the reasoning that "the embed brings its own
            # thumbnail" -- true of the player once it opens, and not true of the
            # CARD, which is what a visitor actually sees. Twelve empty tiles.
            # (client feedback 2026-08-21)
            #
            # Still no duration. YouTube does not publish one on a thumbnail URL,
            # and inventing a running time for a film we have never opened is
            # exactly the kind of made-up number this project has had to strip
            # out before. A card with no duration shows no badge.
            thumb = yt_thumbs.get(slug)
            if not thumb:
                print("  ! %s: no local cover — run tools/fetch-youtube-thumbs.py"
                      % slug)
            item.update({
                "youtubeId": copy["youtubeId"],
                "watch": copy.get("watch"),
                "ratio": copy.get("ratio", "16:9"),
                "poster": thumb["poster"] if thumb else None,
                "dur": None, "video": None,
            })
            item.update(img_fields(thumb.get("posterMeta") if thumb else None))
        else:
            fv = by_slug.get(slug)
            if not fv:
                print("  ! %s: host is drive but the importer found no such video" % slug)
                continue
            if not fv["videoPresent"]:
                print("  ! %s: source video missing, shipping poster-only" % slug)
            item.update({
                "poster": fv["poster"],
                "dur": fv["dur"],      # None -> the card renders no duration badge
                "video": links.get(fv["srcVideo"]),
                "ratio": copy.get("ratio", "16:9"),
                "youtubeId": None, "watch": None,
            })
            # srcset/sizes/w/h describe `poster`. `sizes` is the 395-448px card
            # thumbnail; the 880px modal stage sets its own.
            item.update(img_fields(fv.get("posterMeta")))
        out.append(item)

    seen = {i["slug"] for i in out}
    for slug in by_slug:
        if slug not in seen:
            print("  ! %s: imported but no copy in content-meta.json, not shipped" % slug)
    return out


def build_gallery(manifest, meta):
    g = meta["gallery"]
    subjects, sizes = g["subjects"], g["sizes"]
    seen = {s: 0 for s in subjects}
    out = []

    for i, item in enumerate(manifest["gallery"]):
        subject = subjects[i % len(subjects)]
        size = sizes[i % len(sizes)]
        pool = g["prices"][subject]
        price = pool[seen[subject] % len(pool)]
        seen[subject] += 1

        # .land / --r in Gallery.dc.html are CSS aspect-ratio => WIDTH / HEIGHT.
        # The manifest stores h/w, so invert. A wrong value here visibly squashes
        # the artwork, which is why every piece gets a real measured number.
        ratio = round(item["w"] / item["h"], 3)

        # Placeholder sale flags so the layout can be judged: every third piece
        # shows a struck original price and a ribbon. Crystal sets the real ones.
        was = int(round(price * 1.25 / 5.0)) * 5 if i % 3 == 1 else None

        piece = {
            "title": "%s No.%d" % (subject, seen[subject]),
            "img": "gallery/" + item["img"],   # cardHTML prefixes 'img/'
            "tags": [g["medium"], subject],
            "price": price,
            "was": was,
            "date": "2026-%02d-%02d" % (7 - (i // 3), 28 - (i % 3) * 9),
            "orig": subject == "Original painting",
            "size": size,
            "desc": g["desc"],
            "ratio": ratio,
        }
        # srcset/sizes/w/h describe `img`. Note these paths are site-relative
        # ("img/gallery/g01-320.jpg") while `img` is not — Gallery.dc.html
        # prefixes 'img/' to `img` and must NOT prefix `srcset`.
        piece.update(img_fields(item.get("meta")))
        out.append(piece)
    return out


def write_js(path, varname, payload, extra=""):
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(BANNER)
        fh.write("window.%s = %s;\n" % (varname, json.dumps(payload, indent=2, ensure_ascii=False)))
        if extra:
            fh.write(extra)
    print("   wrote %s (%d KB)" % (os.path.relpath(path, SITE_DIR),
                                   os.path.getsize(path) // 1024))


def main():
    manifest_path = os.path.join(TOOLS, "asset-manifest.json")
    if not os.path.exists(manifest_path):
        sys.exit("run tools/import-assets.py first")

    manifest, meta = load(manifest_path), load(os.path.join(TOOLS, "content-meta.json"))

    links = load_video_links()
    print("video links: %d mapped" % len(links))

    # Optional, and its absence is a warning rather than an error: the file needs
    # the network to produce and a contributor without it should still be able to
    # rebuild the data. Missing means the YouTube cards ship without covers, and
    # build_free_videos says so per film.
    yt_path = os.path.join(TOOLS, "youtube-thumbs.json")
    yt_thumbs = load(yt_path).get("thumbs", {}) if os.path.exists(yt_path) else {}
    print("youtube covers: %d" % len(yt_thumbs))

    print("courses:")
    courses = build_courses(manifest, meta, links)
    free = build_free_videos(manifest, meta, links, yt_thumbs)
    gallery = build_gallery(manifest, meta)

    helpers = (
        "\n"
        "/* Legacy id from the single-course prototype — keep resolving so old\n"
        "   links and bookmarks do not silently 404. */\n"
        "window.CAS_COURSE_ALIASES = { 'cloud-painting': 'clouds-beginner' };\n"
        "\n"
        "window.CAS_COURSE_BY_ID = function (id) {\n"
        "  var list = window.CAS_COURSES || [];\n"
        "  var want = window.CAS_COURSE_ALIASES[id] || id;\n"
        "  for (var i = 0; i < list.length; i++) { if (list[i].id === want) return list[i]; }\n"
        "  return null;\n"
        "};\n"
        "\n"
        "/* Every course page falls back to this one rather than throwing. */\n"
        "window.CAS_DEFAULT_COURSE = 'clouds-beginner';\n"
    )

    write_js(os.path.join(JS, "course-data.js"), "CAS_COURSES", courses, helpers)
    write_js(os.path.join(JS, "free-videos-data.js"), "CAS_FREE_VIDEOS", free)
    write_js(os.path.join(JS, "gallery-data.js"), "CAS_GALLERY", gallery)
    write_js(os.path.join(JS, "static-images.js"), "CAS_IMG",
             manifest.get("static", {}), STATIC_HELPER)

    print("\ncourses=%d  lessons=%d  gallery=%d  freeVideos=%d" % (
        len(courses), sum(len(c["lessons"]) for c in courses), len(gallery), len(free)))


if __name__ == "__main__":
    main()
